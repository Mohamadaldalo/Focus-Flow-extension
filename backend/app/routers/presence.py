"""
backend/app/routers/presence.py  ← NEW FILE, create this

Heartbeat and online-count endpoints for the live presence tracker.

Flow:
  1. Browser generates a UUID on first load (stored in localStorage as focusflow_client_id)
  2. Every 30 seconds the frontend calls  POST /presence/heartbeat  with that client_id
  3. The backend upserts the last_seen timestamp for that client_id
  4. GET /presence/online  counts rows where last_seen > now - 120s  and returns the number
  5. Old rows (> 5 minutes) are pruned on every heartbeat to keep the table clean
"""
from datetime import datetime, timedelta

from fastapi import APIRouter, Depends
from pydantic import BaseModel
from sqlalchemy.orm import Session

from .. import models
from ..database import get_db

router = APIRouter(prefix="/presence", tags=["presence"])

ONLINE_WINDOW_SECONDS = 120   # a client is "online" if pinged in the last 2 minutes
PRUNE_AFTER_SECONDS   = 300   # delete rows older than 5 minutes


class HeartbeatRequest(BaseModel):
    client_id: str              # UUID generated by the browser
    label: str | None = None    # optional friendly name ("Mohammad's laptop")


class OnlineResponse(BaseModel):
    count: int
    client_ids: list[str]       # lets the frontend know its own id is registered


@router.post("/heartbeat", status_code=204)
def heartbeat(payload: HeartbeatRequest, db: Session = Depends(get_db)):
    """
    Called by the frontend every 30 seconds while the app is open.
    No authentication required — presence is anonymous (client_id only).
    """
    now = datetime.utcnow()

    # Upsert: update last_seen if exists, insert if new
    existing = db.get(models.OnlinePresence, payload.client_id)
    if existing:
        existing.last_seen = now
        if payload.label:
            existing.label = payload.label
    else:
        db.add(models.OnlinePresence(
            client_id=payload.client_id,
            last_seen=now,
            label=payload.label,
        ))

    # Prune stale rows while we're here
    cutoff = now - timedelta(seconds=PRUNE_AFTER_SECONDS)
    db.query(models.OnlinePresence).filter(
        models.OnlinePresence.last_seen < cutoff
    ).delete(synchronize_session=False)

    db.commit()


@router.get("/online", response_model=OnlineResponse)
def online_count(db: Session = Depends(get_db)):
    """
    Returns the number of clients that have pinged in the last 2 minutes.
    No authentication required — count is public information.
    """
    cutoff = datetime.utcnow() - timedelta(seconds=ONLINE_WINDOW_SECONDS)
    rows = (
        db.query(models.OnlinePresence)
        .filter(models.OnlinePresence.last_seen >= cutoff)
        .all()
    )
    return OnlineResponse(count=len(rows), client_ids=[r.client_id for r in rows])